// Han radicals and strokes read as the ideographs they stand for. A font
// can draw 门 and the radical ⻔ with one glyph, and a writer that maps its
// glyphs back to text through the font's own character map can pick the
// radical: Chrome's PDFs read 开门 as 开⻔.

// ideograph is the unified ideograph the radical or stroke c stands for,
// or c.
func ideograph(c rune) rune {
	switch {
	case c >= 0x2F00 && c <= 0x2FDF:
		// The Kangxi radicals, which NFKC takes to their ideographs.
		r, _ := utf8.DecodeRuneInString(norm.NFKC.String(string(c)))
		return r
	case c >= 0x2E80 && c <= 0x2EFF || c >= 0x31C0 && c <= 0x31EF:
		if r, ok := radicals[c]; ok {
			return r
		}
	}
	return c
}

